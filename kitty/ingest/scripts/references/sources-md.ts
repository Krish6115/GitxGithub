// Renders Git/references/SOURCES.md.
import { RETRIEVED, UPSTREAM } from './pins.js';
import type { SourceKind } from './spec.js';

export interface BuiltPart {
  label: string;
  url: string;
  kind: SourceKind;
}
export interface BuiltFile {
  out: string;
  words: number;
  parts: BuiltPart[];
}

const rel = (out: string): string =>
  out.startsWith('Git/references/') ? out.slice('Git/references/'.length) : `../../${out}`;
const link = (out: string): string => `[${out.split('/').pop() ?? out}](${rel(out)})`;
const lic = (k: SourceKind): string => `[${UPSTREAM[k].license.name}](${UPSTREAM[k].license.url})`;
const pin = (k: SourceKind): string => `[${UPSTREAM[k].repo}](https://github.com/${UPSTREAM[k].repo}) @ \`${UPSTREAM[k].sha.slice(0, 7)}\``;

export function renderSourcesMd(files: BuiltFile[]): string {
  const sources = new Map<string, BuiltPart & { files: Set<string> }>();
  for (const f of files) {
    for (const p of f.parts) {
      const s = sources.get(p.url) ?? { ...p, files: new Set<string>() };
      s.files.add(f.out);
      sources.set(p.url, s);
    }
  }
  const table = (kind: SourceKind, head: string): string =>
    [`| ${head} | Used in |`, '|---|---|',
      ...[...sources.values()].filter((s) => s.kind === kind)
        .map((s) => `| [${s.label.replace(/^(GitHub Docs|Git documentation): /, '')}](${s.url}) | ${[...s.files].map(link).join(', ')} |`),
    ].join('\n');
  const kindsOf = (f: BuiltFile): string => [...new Set(f.parts.map((p) => UPSTREAM[p.kind].license.name))].join(', ');

  return `# Sources and attribution for Kitty's knowledge references

The Markdown files in \`Git/references/\` and \`Scenario-Based_Guide/references/\` are **adapted excerpts** from
openly licensed sources. They give Kitty, the GitxGithub companion, grounded material for topics that the
repository's own PDFs don't cover (see \`kitty/ingest/AUDIT.md\`). They are generated by
\`kitty/ingest/scripts/references/\`; see \`kitty/ingest/README.md\` to regenerate them.

**These files are not covered by the repository's MIT license.** Each excerpt keeps the license of its source,
as stated at the top of every file and on every excerpt.

## Licenses

| Source | Author / owner | License | Upstream (pinned) |
|---|---|---|---|
| *Pro Git*, 2nd edition | Scott Chacon and Ben Straub (Apress) | ${lic('progit')} | ${pin('progit')} |
| GitHub Docs | GitHub, Inc. | ${lic('ghdocs')} (prose; code samples are MIT) | ${pin('ghdocs')} |
| Git documentation | The Git Project | ${lic('git')} | ${pin('git')} \`Documentation/\` |

Retrieved ${RETRIEVED}.

**What was changed:** only selected sections were kept. AsciiDoc and Liquid were converted to Markdown, and
images and figures were removed; references to figures name the figure's caption instead. GitHub Docs content is rendered
for GitHub.com only (Enterprise Server variants removed), with product-name variables and shared snippets
expanded. Wording is otherwise unchanged.

**License notes:**
- *ShareAlike (Pro Git):* anything adapted from the Pro Git excerpts must stay under CC BY-NC-SA 3.0.
- *NonCommercial (Pro Git):* fine for this non-commercial hackathon project. Revisit if Kitty is ever offered commercially.
- *Attribution:* when Kitty answers from these files, it cites the source named in the excerpt's "Source:" line.

## Pro Git, 2nd edition (${UPSTREAM.progit.license.name})

${table('progit', 'Section')}

## GitHub Docs (${UPSTREAM.ghdocs.license.name})

${table('ghdocs', 'Article')}

## Git documentation (${UPSTREAM.git.license.name})

${table('git', 'Manual page')}

## Files

| File | Words | Licenses |
|---|---:|---|
${files.map((f) => `| ${link(f.out)} | ${f.words.toLocaleString('en-US')} | ${kindsOf(f)} |`).join('\n')}
`;
}
